"""Regenerate submission examples from the actual search implementation."""

from pathlib import Path

from morris.board import Board
from morris.search import fixed_search

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures"


def describe(script, name, depth, result):
    return (f"$ python3 {script}.py tests/fixtures/{name}.txt /tmp/morris-example.txt {depth}\n"
            f"Board Position: {result.board}\n"
            f"Positions evaluated by static estimation: {result.evaluations}\n"
            f"MINIMAX estimate: {result.score}\n")


def main():
    FIXTURES.mkdir(parents=True, exist_ok=True)
    boards = {
        "empty": "x" * 23,
        "opening": "WxxBxxxxxxxxxxxxxxxxxxx",
        "opening-forks": "WxBxxxxWxxxxBxxxxxxxxxx",
        "handout-game": "xxxxxBxWWWWWBBBBxxxxxxx",
        "handout-game-2": "WxWWxWWWWWBBBBBBBBxxxxx",
    }
    for name, value in boards.items():
        FIXTURES.joinpath(name + ".txt").write_text(value + "\n")
    text = ["MORRIS VARIANT: REPRODUCIBLE EXAMPLES\n",
            "Generated by python3 -m tools.generate_examples. Depth counts plies.\n"
            "Each output file contains the Board Position line's 23-character value.\n"
            "Scores from different evaluators have different scales.\n"]
    for name, opening, depth in (("empty", True, 3), ("handout-game", False, 3)):
        board = Board.parse(boards[name])
        suffix = "Opening" if opening else "Game"
        plain = fixed_search(board, depth, opening)
        pruned = fixed_search(board, depth, opening, pruning=True)
        assert (plain.board, plain.score) == (pruned.board, pruned.score)
        assert pruned.evaluations < plain.evaluations
        text.extend([f"ALPHA-BETA COMPARISON: {name}\nInput: {board}\n",
                     describe("MiniMax" + suffix, name, depth, plain),
                     describe("AB" + suffix, name, depth, pruned),
                     f"Same move and estimate; {plain.evaluations - pruned.evaluations} fewer leaf evaluations.\n"])
    reasons = {
        "opening": "White chooses g0 (index 2) instead of d0 (index 1). Both threaten the a0-d0-g0 mill, "
                   "but g0 participates in three mills and offers better adjacency than d0, which belongs "
                   "to only one mill. Material alone cannot distinguish these moves.",
        "opening-forks": "White chooses g3 (index 13) instead of d0 (index 1). The improved move gives "
                         "White nine adjacent movement options instead of six, and three potential "
                         "fork-creating placements instead of zero. These are positional preferences, "
                         "not a proof of a forced win.",
    }
    for name, reason in reasons.items():
        board = Board.parse(boards[name])
        plain = fixed_search(board, 2, True)
        stronger = fixed_search(board, 2, True, enhanced=True)
        assert plain.board != stronger.board
        text.extend([f"IMPROVED EVALUATION COMPARISON: {name}\nInput: {board}\n",
                     describe("MiniMaxOpening", name, 2, plain),
                     describe("MiniMaxOpeningImproved", name, 2, stronger),
                     reason + "\n"])
    board = Board.parse(boards["handout-game"])
    for script, opening, side, enhanced in (
        ("MiniMaxOpeningBlack", True, "B", False),
        ("MiniMaxGameBlack", False, "B", False),
        ("MiniMaxGameImproved", False, "W", True),
    ):
        text.append(describe(script, "handout-game", 2,
                             fixed_search(board, 2, opening, side=side, enhanced=enhanced)))
    text.append("Black programs report estimates from Black's perspective after color swapping.\n"
                "Tournament commands and historical practice results are documented in README.md.\n")
    ROOT.joinpath("Examples.txt").write_text("\n".join(text))


if __name__ == "__main__":
    main()
